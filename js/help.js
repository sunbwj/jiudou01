    /* ---------- 附录：功能地图（读当前账号的导航权限） ---------- */
    function flattenNav(nodes, trail, out) {
        if (!nodes || !nodes.length) { return out; }
        for (var i = 0; i < nodes.length; i++) {
            var n = nodes[i] || {};
            var path = trail.concat([n.nameCn || '']);
            var items = n.items || [];
            if (items.length) {
                var groupText = path.join(' / ');
                for (var j = 0; j < items.length; j++) {
                    var it = items[j] || {};
                    out.push({ group: groupText, name: it.nameCn || '', path: it.path || '' });
                }
            } else if (n.path) {
                /* hasChild=0 的菜单组自身就是叶子页 */
                out.push({ group: trail.join(' / ') || '—', name: n.nameCn || '', path: n.path || '' });
            }
            if (n.children && n.children.length) { flattenNav(n.children, path, out); }
        }
        return out;
    }

