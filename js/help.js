    function fallbackNavMap(reason) {
        /* 取不到真实菜单时的兜底：按内置页面清单的章节分组列出，至少不空着 */
        var groups = [], seen = {};
        for (var i = 0; i < PAGES.length; i++) {
            var p = PAGES[i];
            if (p.file === 'help.html' || p.file === 'main.html' || p.file === 'login.html') { continue; }
            var ch = chapterById(p.ch);
            if (!ch) { continue; }
            if (!seen[ch.id]) { seen[ch.id] = { group: ch.no + ' ' + ch.name, name: p.title, path: p.file }; groups.push(seen[ch.id]); }
        }
        var html = '<div class="help-tip help-tip--warn"><span class="help-tip__label">未读到实时菜单</span>' +
            esc(reason || '未登录或接口不可用') + '，下面按系统内置页面清单列出（登录后再打开本页可看到与权限一致的实时结果）。</div>';
        html += navRowsHtml(groups);
        $('#helpNavMap').html(html);
    }

    function loadNavMap() {
        var host = document.getElementById('helpNavMap');
        if (!host) { return; }
        if (!window.Api || !window.Api.nav || !window.Api.nav.get) {
            fallbackNavMap('数据服务未加载');
            return;
        }
        var token = '';
        try {
            var raw = window.localStorage.getItem(SESSION_KEY);
            token = raw ? String((JSON.parse(raw) || {}).token || '') : '';
        } catch (e) { token = ''; }

        window.Api.nav.get(token).done(function (res) {
            var data = (res && res.data) || res || {};
            var groups = data.groups || [];
            var list = flattenNav(groups, [], []);
            if (!list.length) {
                fallbackNavMap('当前账号没有可见菜单项');
                return;
            }
            var meta = '实时读取：当前账号可访问 <b>' + list.length + '</b> 个菜单项';
            if (data.roleNames) { meta += '，所属角色 <b>' + esc(data.roleNames) + '</b>'; }
            if (data.groupCount) { meta += '，菜单组 ' + data.groupCount + ' 个'; }
            var html = '<div class="help-filter"><span class="help-filter__hint">' + meta + '</span></div>';
            html += navRowsHtml(list);
            $('#helpNavMap').html(html);
        }).fail(function () {
            fallbackNavMap('接口返回失败');
        });
    }

